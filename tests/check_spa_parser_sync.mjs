#!/usr/bin/env node
// Keeps site/index.html and the Node modules in sync.
//
//   node tests/check_spa_parser_sync.mjs           check, exit 1 on any difference
//   node tests/check_spa_parser_sync.mjs --write   regenerate the modules and the demo block
//
// * The block between "// ==== BEGIN TEMPO PARSER ====" and "// ==== END TEMPO PARSER ===="
//   in site/index.html must equal the same block in tools/tempo_parse.mjs (same for
//   TEMPO ANALYSIS and tools/tempo_analysis.mjs). The modules are that block plus a fixed
//   header and export footer, so the code Node tests import is the code the page runs.
// * The demo traces embedded in the page must equal the files under samples/.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const HTML = join(ROOT, "site", "index.html");
const write = process.argv.includes("--write");

const MODULES = [
  {
    tag: "TEMPO PARSER",
    file: join(ROOT, "tools", "tempo_parse.mjs"),
    head: "// Tempo-Trace v1 parser as an ES module for Node and other tools.\n" +
          "// GENERATED from site/index.html by `node tests/check_spa_parser_sync.mjs --write`. Do not edit.\n\n",
    foot: "\nexport default TempoParse;\n" +
          "export const {\n  ALPHABET_CHARS, FLAG_ORDER, FLAG_NAMES, MAX_DEPTH, RECORD_RE, ERRORS,\n" +
          "  TempoFormatError, stripWs, decode, decodeName, encodeName, encodeNumber, encode,\n" +
          "  normalizeJson, dumpJson, extractTraces, load\n} = TempoParse;\n"
  },
  {
    tag: "TEMPO ANALYSIS",
    file: join(ROOT, "tools", "tempo_analysis.mjs"),
    head: "// Tempo viewer analysis (self-time, critical path, diff, stats, converters) as an ES module.\n" +
          "// GENERATED from site/index.html by `node tests/check_spa_parser_sync.mjs --write`. Do not edit.\n\n" +
          "import TempoParse from \"./tempo_parse.mjs\";\n\n",
    foot: "\nexport default TempoAnalysis;\n" +
          "export const {\n  poolOf, isCpuPool, has, model, selfTime, criticalPath, byPath, diff, percentile, summary,\n" +
          "  stats, findings, pools, toChrome, toFolded, LANE_MIXED, LANE_LIMBO\n} = TempoAnalysis;\n"
  }
];

// Demo traces bundled into the page (all invented, from tools/gen_traces.py).
const DEMOS = [
  ["find-healthy", "samples/find-healthy.header"],
  ["find-saturated", "samples/find-saturated.header"],
  ["pipeline", "samples/pipeline.header"],
  ["small", "samples/small.header"],
  ["diff-before", "samples/diff/before.header"],
  ["diff-after", "samples/diff/after.header"]
];
const BATCH = Array.from({ length: 30 }, (_, i) => "samples/batch/find-" + String(i + 1).padStart(2, "0") + ".header");
const DEMO_BEGIN = "<!-- BEGIN DEMO TRACES (generated by tests/check_spa_parser_sync.mjs --write) -->";
const DEMO_END = "<!-- END DEMO TRACES -->";

function block(text, tag, where) {
  const begin = "// ==== BEGIN " + tag + " ====";
  const end = "// ==== END " + tag + " ====";
  const i = text.indexOf(begin);
  const j = text.indexOf(end);
  if (i < 0 || j < i) throw new Error(where + ": markers for " + tag + " not found");
  return text.slice(i, j + end.length) + "\n";
}

function demoBlock() {
  const read = (p) => readFileSync(join(ROOT, p), "utf8").replace(/\s+/g, "");
  const lines = DEMOS.map(([k, p]) => "  " + JSON.stringify(k) + ": " + JSON.stringify(read(p)));
  lines.push("  \"batch\": [\n" + BATCH.map((p) => "    " + JSON.stringify(read(p))).join(",\n") + "\n  ]");
  return DEMO_BEGIN + "\n<script type=\"application/json\" id=\"tempo-demos\">\n{\n" + lines.join(",\n") + "\n}\n</script>\n" + DEMO_END;
}

let html = readFileSync(HTML, "utf8");
let problems = 0;

for (const m of MODULES) {
  const want = m.head + block(html, m.tag, "site/index.html") + m.foot;
  const have = existsSync(m.file) ? readFileSync(m.file, "utf8") : "";
  if (have === want) { console.log("ok   " + m.tag + " == " + m.file.slice(ROOT.length + 1)); continue; }
  if (write) { writeFileSync(m.file, want); console.log("wrote " + m.file.slice(ROOT.length + 1)); continue; }
  problems++;
  const a = have.split("\n"), b = want.split("\n");
  let k = 0;
  while (k < a.length && k < b.length && a[k] === b[k]) k++;
  console.log("FAIL " + m.tag + ": " + m.file.slice(ROOT.length + 1) + " differs from site/index.html at line " + (k + 1));
  console.log("     module: " + JSON.stringify(a[k]));
  console.log("     page:   " + JSON.stringify(b[k]));
}

const i = html.indexOf(DEMO_BEGIN), j = html.indexOf(DEMO_END);
if (i < 0 || j < i) { problems++; console.log("FAIL demo traces: markers not found in site/index.html"); }
else {
  const want = demoBlock();
  const have = html.slice(i, j + DEMO_END.length);
  if (have === want) console.log("ok   demo traces == samples/");
  else if (write) { html = html.slice(0, i) + want + html.slice(j + DEMO_END.length); writeFileSync(HTML, html); console.log("wrote demo traces into site/index.html"); }
  else { problems++; console.log("FAIL demo traces in site/index.html differ from samples/ (run with --write)"); }
}

if (problems) { console.log(problems + " problem(s); run `node tests/check_spa_parser_sync.mjs --write` after editing site/index.html"); process.exit(1); }
